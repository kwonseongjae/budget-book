def _grid(row: int, cols: int = 2) -> dict:
    return {"sheetId": SHEET_ID[GUIDE], "startRowIndex": row, "endRowIndex": row + 1,
            "startColumnIndex": 0, "endColumnIndex": cols}


def _fmt(grid: dict, fmt: dict, fields: str) -> dict:
    return {"repeatCell": {"range": grid, "cell": {"userEnteredFormat": fmt}, "fields": fields}}


def guide_requests(start: int = 0) -> list[dict]:
    styles = {
        "title": {"backgroundColor": TITLE_BG, "textFormat": {"fontSize": TITLE_FONT, "bold": True, "foregroundColor": WHITE}},
        "section": {"backgroundColor": SECTION_BG, "textFormat": {"fontSize": SECTION_FONT, "bold": True, "foregroundColor": NAVY}},
        "row": {"textFormat": {"fontSize": BASE_FONT}},
    }
    reqs = []
    for i, (kind, a, _b) in enumerate(CONTENT):
        if i < start:
            continue
        reqs.append(_fmt(_grid(i), styles[kind], "userEnteredFormat(backgroundColor,textFormat)"))
        if kind == "row":  # 왼쪽 항목 이름 칸: 음영 + 굵게, 두 칸 모두 위 정렬
            reqs.append(_fmt(_grid(i, 1), {"backgroundColor": LABEL_BG, "textFormat": {"bold": bool(a), "fontSize": BASE_FONT}, "verticalAlignment": "TOP"},
                             "userEnteredFormat(backgroundColor,textFormat,verticalAlignment)"))
            reqs.append(_fmt({**_grid(i), "startColumnIndex": 1}, {"verticalAlignment": "TOP"}, "userEnteredFormat.verticalAlignment"))
        if kind != "row":
            reqs.append({"mergeCells": {"mergeType": "MERGE_ALL", "range": _grid(i)}})
    body = {"sheetId": SHEET_ID[GUIDE], "startRowIndex": start, "endRowIndex": len(CONTENT),
            "startColumnIndex": 0, "endColumnIndex": 2}
    reqs.append(_fmt(body, {"wrapStrategy": "WRAP"}, "userEnteredFormat.wrapStrategy"))
    line = {"style": "SOLID", "color": {"red": 0.85, "green": 0.85, "blue": 0.85}}
    reqs.append({"updateBorders": {"range": body, "bottom": line, "innerHorizontal": line}})  # 줄마다 가는 구분선
    reqs.append({"autoResizeDimensions": {"dimensions": {"sheetId": SHEET_ID[GUIDE], "dimension": "ROWS",
                                                         "startIndex": start, "endIndex": len(CONTENT)}}})
    return reqs
