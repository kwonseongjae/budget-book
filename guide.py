def bullets(text: str) -> str:
    """두 문장 이상이면 문장마다 한 줄 글머리표로 (한눈에 읽히게). 한국어 문장 끝('다·요·음·임·까·죠' + 마침표 + 공백)에서만 자른다."""
    parts = re.split(r"(?<=[다요음임까죠)])\.\s+", text.strip())
    return text if len(parts) < 2 else "\n".join("• " + (p if p.endswith(".") else p + ".") for p in parts)


